const makeApproach = (
  problem: string,
  [id, name, profile, requires = []]: ApproachOption,
): ApproachInput => {
  const base = profiles[profile],
    tuning = familyTuning[problem] || {};
  const tuned = Object.fromEntries(
    (Object.entries(tuning) as [keyof ApproachMetrics, number][]).map(([key, multiplier]) => [
      key,
      ['days', 'debt', 'upkeep'].includes(key)
        ? Math.ceil(base[key] * multiplier)
        : base[key] * multiplier,
    ]),
  );
  return {
    id: problem + '_' + id,
    problem,
    name,
    ...base,
    ...tuned,
    profile,
    requires,
    description: name + '.',
    tradeoff: base.summary,
  };
};
